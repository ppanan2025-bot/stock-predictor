#!/usr/bin/env node
// Regenerates db/init/06-closures.sql from the NYSE calendar (src/market/calendar.mjs) + config price.extra_closures.
// test/calendar.test.mjs asserts the committed file equals this output. Usage: node scripts/gen-closures.mjs [--from 2023 --to 2027]
import fs from 'node:fs';
import path from 'node:path';
import { root } from '../src/lib/env.mjs';
import { closuresBetween } from '../src/market/calendar.mjs';
import { parseArgs } from '../src/lib/cli.mjs';

export const CLOSURE_YEARS = [2023, 2027];

export function closuresSql(from = CLOSURE_YEARS[0], to = CLOSURE_YEARS[1]) {
  const rows = closuresBetween(from, to).map((c) => `  ('${c.date}', '${c.name.replaceAll("'", "''")}')`);
  return `-- GENERATED by scripts/gen-closures.mjs (NYSE full-day closures ${from}-${to}). Idempotent; applied by npm run db:migrate.\n`
    + `INSERT IGNORE INTO nyse_closures (closure_date, name) VALUES\n${rows.join(',\n')};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const a = parseArgs();
  fs.writeFileSync(path.join(root, 'db/init/06-closures.sql'), closuresSql(Number(a.from ?? CLOSURE_YEARS[0]), Number(a.to ?? CLOSURE_YEARS[1])));
  console.log('wrote db/init/06-closures.sql');
}
