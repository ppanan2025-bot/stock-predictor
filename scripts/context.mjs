#!/usr/bin/env node
// npm run context -- [--ticker T[,T2]] [--stdout]
// GENERATES context/companies/<T>.md (PLAN §8 /company-context; never hand-edited): profile from config/companies.json, latest
// deterministic features (recomputed from verified closes; stored quant_features sha compared), top 10 verified research notes
// with ids, recent verified news ids, and the last 3 predictions with outcomes. Reads the DB as stock_ro only.
import fs from 'node:fs';
import path from 'node:path';
import { root } from '../src/lib/env.mjs';
import { parseArgs } from '../src/lib/cli.mjs';
import { roPool, closePools } from '../src/lib/db.mjs';
import { clean } from '../src/lib/repo.mjs';
import { loadCompanies } from '../src/verify/config.mjs';
import { loadFeatureInputs, featuresFor } from '../src/quant/featureStore.mjs';

const args = parseArgs();
const q = async (sql, a = []) => clean((await roPool().query(sql, a))[0]);
const pct = (v) => (v === null || v === undefined ? 'n/a' : `${(Number(v) * 100).toFixed(2)}%`);
const md = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

export function renderContext({ co, f, sha, stored, notes, news, preds, generatedAt }) {
  const L = [];
  L.push(`# ${co.ticker} — ${co.name}`, '', `<!-- GENERATED by npm run context at ${generatedAt}. Do not edit; regenerate. -->`, '');
  L.push('## Profile', '', `- Exchange: ${co.exchange}; sector: ${co.sector ?? 'n/a'}; industry: ${co.industry ?? 'n/a'}`,
    `- CIK: ${co.cik ?? 'none (no SEC filings source)'}; IR domains: ${(co.ir_domains ?? []).join(', ') || 'none'}`,
    `- Peers: ${(co.peers ?? []).join(', ') || 'none'}; listed: ${co.listed_on}${co.note ? `; note: ${co.note}` : ''}`, '');
  L.push('## Latest features (verified closes only)', '');
  if (!f) L.push('No verified close yet.', '');
  else {
    L.push(`As of ${f.month} (close ${f.close}, ${f.n_months} verified months, code ${f.code_version}, sha256 ${sha.slice(0, 16)}; stored row: ${stored ? (stored.features_sha256 === sha ? 'matches' : 'STALE, run compute_features') : 'not stored yet'}).`, '',
      '| r1 | r3 | r6 | r12 | vol12 | vol36 | mdd12 | dist 12m high | up-month rate 36m | mom_z | rel r3 vs peers |', '|---|---|---|---|---|---|---|---|---|---|---|',
      `| ${pct(f.r1)} | ${pct(f.r3)} | ${pct(f.r6)} | ${pct(f.r12)} | ${pct(f.vol12)} | ${pct(f.vol36)} | ${pct(f.mdd12)} | ${pct(f.dist_12m_high)} | ${f.up_rate36 ?? 'n/a'} | ${f.mom_z ?? 'n/a'} | ${pct(f.rel_r3_peers)} |`, '',
      `Flags: ${f.flags.length ? f.flags.join(', ') : 'none'}${f.gap_months.length ? `; gaps: ${f.gap_months.join(', ')}` : ''}. Null = insufficient verified history (never extrapolated).`, '');
  }
  L.push('## Top verified research notes', '');
  if (!notes.length) L.push('None yet. Run /research-company.', '');
  else { L.push('| note | source | date | category | claim |', '|---|---|---|---|---|'); for (const n of notes) L.push(`| N${n.note_id} | [S${n.source_id}] | ${n.as_of_date ?? '-'} | ${n.category} | ${md(n.claim)} |`); L.push(''); }
  L.push('## Recent verified news', '');
  if (!news.length) L.push('None.', '');
  else for (const n of news) L.push(`- [S${n.source_id}] ${String(n.published_at ?? '').slice(0, 10)} ${n.status}: ${md(n.title)}`);
  L.push('', '## Last predictions', '');
  if (!preds.length) L.push('None yet.', '');
  else for (const p of preds) L.push(`- #${p.id} ${p.target_month} v${p.version} ${p.status}: ${p.direction} p_up=${p.p_up} mid=${pct(p.exp_return_mid)}${p.actual_return !== null && p.actual_return !== undefined ? ` -> actual ${pct(p.actual_return)} hit=${p.direction_hit}` : ''}`);
  L.push('', 'Inbox leads (inbox/leads/) are unverified search hints only and are never listed or cited here.', '');
  return L.join('\n');
}

async function main() {
  const companies = loadCompanies().companies;
  const tickers = args.ticker && args.ticker !== true ? String(args.ticker).toUpperCase().split(',') : companies.filter((c) => c.active).map((c) => c.ticker);
  const inputs = await loadFeatureInputs(roPool());
  const generatedAt = new Date().toISOString();
  for (const t of tickers) {
    const co = companies.find((c) => c.ticker === t);
    if (!co) { console.error(`[context] unknown ticker ${t}`); process.exitCode = 1; continue; }
    const r = featuresFor(inputs, t);
    const f = r.error ? null : r.features;
    const stored = f ? (await q('SELECT features_sha256 FROM quant_features WHERE ticker = ? AND month = ?', [t, f.month]))[0] ?? null : null;
    const notes = await q(`SELECT r.id AS note_id, r.source_id, r.category, r.claim, r.as_of_date FROM research_notes r JOIN sources s ON s.id = r.source_id
      WHERE r.ticker = ? AND r.status = 'verified' AND s.verification_status IN ('verified','corroborated') ORDER BY (s.tier = 'primary') DESC, COALESCE(r.as_of_date, r.created_at) DESC, r.id DESC LIMIT 10`, [t]);
    const news = await q(`SELECT n.source_id, n.title_submitted AS title, COALESCE(s.published_at_fetched, n.published_at_submitted) AS published_at, n.status
      FROM news_items n JOIN sources s ON s.id = n.source_id WHERE n.ticker = ? AND n.status IN ('verified','corroborated') AND s.verification_status IN ('verified','corroborated')
      ORDER BY COALESCE(s.published_at_fetched, n.published_at_submitted) DESC LIMIT 10`, [t]);
    const preds = await q(`SELECT p.id, p.target_month, p.version, p.status, p.direction, p.p_up, p.exp_return_mid, o.actual_return, o.direction_hit
      FROM predictions p LEFT JOIN prediction_outcomes o ON o.prediction_id = p.id WHERE p.ticker = ? ORDER BY p.target_month DESC, p.version DESC LIMIT 3`, [t]);
    const text = renderContext({ co, f, sha: r.features_sha256 ?? '', stored, notes, news, preds, generatedAt });
    if (args.stdout) { console.log(text); continue; }
    const file = path.join(root, 'context', 'companies', `${t}.md`);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`[context] wrote ${path.relative(root, file)} (${f ? `features ${f.month}` : 'no features'}, ${notes.length} notes, ${news.length} news, ${preds.length} predictions)`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch((e) => { console.error(`[context] ${e.message}`); process.exitCode = 1; }).finally(() => closePools());
